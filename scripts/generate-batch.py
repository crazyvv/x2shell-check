#!/usr/bin/env python3
"""Extract the no-argument, JSON-only scanner from the Bash source."""

import argparse
from pathlib import Path


def render(source):
    lines = source.splitlines(keepends=True)
    if not lines or not lines[0].startswith("#!"):
        raise ValueError("expected a Bash shebang")
    output = [lines[0], "# Generated by scripts/generate-batch.py from x2shell-check.sh.\n",
              "# Java, NGINX and Apache local inventory. No arguments. JSON to stdout.\n"]
    full_only = False
    for number, line in enumerate(lines[1:], 2):
        marker = line.rstrip("\n")
        if marker == "# @full-begin":
            if full_only:
                raise ValueError(f"nested full-only block at line {number}")
            full_only = True
        elif marker == "# @full-end":
            if not full_only:
                raise ValueError(f"unmatched full-only end at line {number}")
            full_only = False
        elif line.startswith("# @batch "):
            if full_only:
                raise ValueError(f"batch line inside a full-only block at line {number}")
            output.append(line.removeprefix("# @batch "))
        elif not full_only:
            output.append(line)
    if full_only:
        raise ValueError("unterminated full-only block")
    return "".join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    generated = render((directory / "x2shell-check.sh").read_text(encoding="utf-8"))
    output = directory / "x2shell-batch.sh"
    if args.check:
        if not output.is_file() or output.read_text(encoding="utf-8") != generated:
            parser.exit(1, "x2shell-batch.sh is stale. Run python3 scripts/generate-batch.py.\n")
    else:
        output.write_text(generated, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
